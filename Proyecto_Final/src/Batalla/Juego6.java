    private void btnatacarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnatacarActionPerformed
 JOptionPane.showMessageDialog(null, "tienes 3 golpes para matarlo");
String[] herramientas = {"hacha", "daga", "flechas", "espada"};
int golpestotales = 0;
int golpes = 3;

for (int i = 0; i < golpes; i++) {
    String opc = (String) JOptionPane.showInputDialog(null, "¿Cuál herramienta eliges para tu golpe número " + (i+1) + "?",
            "Elige una herramienta", JOptionPane.QUESTION_MESSAGE, null, herramientas, herramientas[0]);
    int impacto = 0;

    switch(opc){
        case "hacha":
            JOptionPane.showMessageDialog(null, "Has elegido el hacha");
            impacto = 25;
            break;
        case "daga":
            JOptionPane.showMessageDialog(null, "Has elegido la daga");
            impacto = 15;
            break;
        case "flechas":
            JOptionPane.showMessageDialog(null, "Has elegido las flechas");
            impacto = 30;
            break;
        case "espada":
            JOptionPane.showMessageDialog(null, "Has elegido la espada");
            impacto = 40;
            break;
        default:
            JOptionPane.showMessageDialog(null, "Opcion no valida");
            break;
    }

    golpestotales += impacto;
}

if (golpestotales < 60) {
    JOptionPane.showMessageDialog(null, "el dragon te ha matado");
} else {
    JOptionPane.showMessageDialog(null, "Has vencido al dragón");
    Juego7 jg7 = new Juego7();
    jg7.setVisible(true);
    dispose();
}

    }//GEN-LAST:event_btnatacarActionPerformed

