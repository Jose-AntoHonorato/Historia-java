    private void btnintentarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnintentarActionPerformed
String respuesta = "";


do {
    if (intentos < 3) {
        try {
            int respuestaInt = Integer.parseInt(txtrespuesta.getText());
            if (respuestaInt == 8) {
                Juego4 jg4 = new Juego4();
                jg4.setVisible(true);
                dispose();
                JOptionPane.showMessageDialog(null, "Bien respondido, puedes seguir.");
            } else {
                intentos++; 
                JOptionPane.showMessageDialog(null, "Respuesta incorrecta. Te quedan " + (3 - intentos) + " intentos.");
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Solo números.");
        }
    } else {
        JOptionPane.showMessageDialog(null, "Has fracasado tus intentos.");
        JOptionPane.showMessageDialog(null, "Una manada de lobos te ha matado.");
        respuesta = JOptionPane.showInputDialog("¿Quieres intentarlo de nuevo? (s/n):");
        if (respuesta.equalsIgnoreCase("s")) {
            intentos = 0;
        }
    }
} while (respuesta.equalsIgnoreCase("n"));



    }//GEN-LAST:event_btnintentarActionPerformed

